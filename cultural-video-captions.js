function setCulturalCaptionStatus(message) {
  const status = document.querySelector('#cultural-caption-status');
  if (status) status.textContent = message;
}

function updateCulturalCaption(seconds) {
  const target = document.querySelector('#cultural-caption-text');
  if (!target || !Number.isFinite(seconds)) return;
  const caption = culturalVideoCaptionData.cues
    .filter(cue => cue.start <= seconds && seconds < cue.end)
    .map(cue => cue.text).join('\n');
  if (target.textContent !== caption) target.textContent = caption;
}

function stopCulturalVideoCaptions() {
  const controller = culturalVideoCaptionController;
  culturalVideoCaptionController = null;
  if (!controller) return;
  controller.disposed = true;
  clearTimeout(controller.timeout);
  // Vimeo's destroy() removes its message listener and the old iframe.
  controller.player.destroy().catch(() => {});
}

function startCulturalVideoCaptions() {
  stopCulturalVideoCaptions();
  const iframe = document.querySelector('#cultural-slide-media iframe');
  if (!iframe) return;
  const unavailable = 'Live captions are unavailable. You can still read or download the video transcript below.';
  if (!window.Vimeo || !window.Vimeo.Player) {
    setCulturalCaptionStatus(unavailable);
    return;
  }
  let player;
  try { player = new window.Vimeo.Player(iframe); }
  catch (_) { setCulturalCaptionStatus(unavailable); return; }
  const controller = { player, iframe, seconds: 0, disposed: false, timeout: null, ready: false };
  culturalVideoCaptionController = controller;
  const isCurrent = () => !controller.disposed && culturalVideoCaptionController === controller && iframe.isConnected;
  const sync = data => {
    if (!isCurrent() || !Number.isFinite(data.seconds)) return;
    controller.seconds = data.seconds;
    clearTimeout(controller.timeout);
    if (!controller.ready) {
      controller.ready = true;
      setCulturalCaptionStatus(culturalCaptionPreference.enabled ? 'Captions are on and follow the video.' : 'Captions are off. The transcript remains available below.');
    }
    updateCulturalCaption(data.seconds);
  };
  const failed = () => {
    if (!isCurrent()) return;
    controller.ready = false;
    clearTimeout(controller.timeout);
    const target = document.querySelector('#cultural-caption-text');
    if (target) target.textContent = '';
    setCulturalCaptionStatus(unavailable);
  };
  // Use media time, not a wall-clock timer, so captions follow pause, seek,
  // buffering, playback speed changes, and returning to an earlier cue.
  ['timeupdate', 'seeking', 'seeked', 'play', 'pause', 'ended'].forEach(event => player.on(event, sync));
  player.on('error', failed);
  player.ready().then(() => {
    if (!isCurrent()) return;
    return player.getCurrentTime().then(seconds => sync({ seconds }));
  }).catch(failed);
  controller.timeout = setTimeout(failed, 15000);
}

document.addEventListener('click', event => {
  const button = event.target.closest('[data-cultural-captions-toggle]');
  if (!button) return;
  culturalCaptionPreference.enabled = !culturalCaptionPreference.enabled;
  button.setAttribute('aria-pressed', String(culturalCaptionPreference.enabled));
  button.textContent = `Captions ${culturalCaptionPreference.enabled ? 'on' : 'off'}`;
  document.querySelector('#cultural-caption-display').hidden = !culturalCaptionPreference.enabled;
  if (culturalVideoCaptionController && culturalVideoCaptionController.ready) {
    setCulturalCaptionStatus(culturalCaptionPreference.enabled ? 'Captions are on and follow the video.' : 'Captions are off. The transcript remains available below.');
    updateCulturalCaption(culturalVideoCaptionController.seconds);
  }
});
